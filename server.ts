import express from "express";
import path from "path";
import { createServer as createViteServer } from "vite";
import { GoogleGenAI, Type } from "@google/genai";
import dotenv from "dotenv";

// Load environment variables
dotenv.config();

// Initialize Gemini Client safely
const isApiKeyConfigured = !!process.env.GEMINI_API_KEY && process.env.GEMINI_API_KEY !== "MY_GEMINI_API_KEY";

const ai = isApiKeyConfigured
  ? new GoogleGenAI({
      apiKey: process.env.GEMINI_API_KEY,
      httpOptions: {
        headers: {
          "User-Agent": "aistudio-build",
        },
      },
    })
  : null;

async function startServer() {
  const app = express();
  const PORT = 3000;

  // Configure middleware to parse large payloads
  app.use(express.json({ limit: "20mb" }));

  // Helper utility to safely execute Gemini analysis or generate realistic fallback templates
  app.get("/api/health", (req, res) => {
    res.json({
      status: "ok",
      geminiConnected: isApiKeyConfigured,
      timestamp: new Date().toISOString(),
    });
  });

  // 1. Music Analyzer Endpoint
  app.post("/api/analyze-music", async (req, res) => {
    const { fileName, lyrics, userGenreGuess } = req.body;

    if (!fileName) {
      return res.status(400).json({ error: "No track name or file provided." });
    }

    if (!isApiKeyConfigured || !ai) {
      console.warn("GEMINI_API_KEY is not configured or placeholder. Delivering fallback music analysis.");
      // Serve highly detailed visual simulation data corresponding to the prompt
      return res.json(getFallbackMusicAnalysis(fileName, lyrics, userGenreGuess));
    }

    try {
      const prompt = `
        Analyze this song for a high-fidelity video synchronization task:
        - File Name: "${fileName}"
        - Genre Guess/Clues: "${userGenreGuess || "Dynamic Synthesis"}"
        - Custom Lyrics/Context: "${lyrics || "No lyrics provided"}"

        Provide a highly professional analysis designed to sync video pacing, lighting, motion, and visual transitions perfectly to this music's vibe.
      `;

      const schema = {
        type: Type.OBJECT,
        properties: {
          pacing: {
            type: Type.STRING,
            description: "Pacing of the song, e.g. Fast, Medium, Slow, Dynamic, Polyrhythmic."
          },
          tempo: {
            type: Type.INTEGER,
            description: "Estimated BPM of the music as an integer."
          },
          instrumentation: {
            type: Type.ARRAY,
            items: { type: Type.STRING },
            description: "Dominant instruments present in this track (e.g. Synth, Acoustic Guitar, Heavy Drums, Sub Bass, Piano)."
          },
          keyMood: {
            type: Type.STRING,
            description: "Dominant emotional mood, e.g. Ethereal, Melancholic, High-Energy Cyberpunk, Warm Romance, Cinematic Hype."
          },
          energyCurve: {
            type: Type.STRING,
            description: "Description of the energy progression (e.g., Starts with ambient piano, builds up to an explosive dubstep beat drop, ends in a gentle synth pad fade-out)."
          },
          emotionalTriggers: {
            type: Type.ARRAY,
            items: { type: Type.STRING },
            description: "Psychological emotional feelings generated by this song's structure."
          },
          suggestedTransitionSpeed: {
            type: Type.STRING,
            description: "Exact recommendation for video editors (e.g., rapid cuts on kick drums, slow elegant cross-dissolves)."
          },
          thematicSegments: {
            type: Type.ARRAY,
            items: { type: Type.STRING },
            description: "Estimated song arrangement tags, e.g. ['0:00 - Intro: Ethereal ambience', '0:15 - Verse 1: Subtle drum kick and vocals', '0:30 - Chorus: Explosive drop', '0:45 - Outro: Quiet drone']"
          }
        },
        required: ["pacing", "tempo", "instrumentation", "keyMood", "energyCurve", "emotionalTriggers", "suggestedTransitionSpeed", "thematicSegments"]
      };

      const response = await ai.models.generateContent({
        model: "gemini-3.5-flash",
        contents: prompt,
        config: {
          systemInstruction: "You are a professional musicologist, sound designer, and music video director. Analyze song parameters for video generation.",
          responseMimeType: "application/json",
          responseSchema: schema,
        }
      });

      const parsedResult = JSON.parse(response.text || "{}");
      return res.json(parsedResult);
    } catch (err: any) {
      console.error("Gemini API error during music analysis:", err);
      return res.json(getFallbackMusicAnalysis(fileName, lyrics, userGenreGuess));
    }
  });

  // 2. Reference Videos Analyzer Endpoint
  app.post("/api/analyze-references", async (req, res) => {
    const { files } = req.body; // Array of files { name, description, sizeLabel }

    if (!files || !Array.isArray(files) || files.length === 0) {
      return res.status(400).json({ error: "No reference files uploaded." });
    }

    if (!isApiKeyConfigured || !ai) {
      console.warn("GEMINI_API_KEY is not configured or placeholder. Delivering fallback reference analysis.");
      return res.json(getFallbackReferenceAnalysis(files));
    }

    try {
      const prompt = `
        Analyze these reference videos that the user wants their AI-generated videos to resemble:
        ${JSON.stringify(files)}

        Extract visual characteristics, including motion, emotions/vibes, pacing, lighting, transitions, camera movements, and editing style.
      `;

      const schema = {
        type: Type.ARRAY,
        items: {
          type: Type.OBJECT,
          properties: {
            id: { type: Type.STRING },
            fileName: { type: Type.STRING },
            mimeType: { type: Type.STRING },
            fileSizeLabel: { type: Type.STRING },
            motionDescription: { type: Type.STRING, description: "Detailed motion vectors, e.g. swift panning, handheld shake, slow dolly zoom" },
            emotionsDetected: { type: Type.STRING, description: "Identified emotional tones of the visuals" },
            pacingStyle: { type: Type.STRING, description: "Editing pace, e.g., ambient long cuts, erratic music-synchronized cuts" },
            lightingStyle: { type: Type.STRING, description: "Lighting, e.g., low-key neon glow, high-contrast chiaroscuro, golden hour backlight" },
            transitionsStyle: { type: Type.STRING, description: "Types of visual transitions, e.g., whip pan cuts, soft cross-fades, geometric masks" },
            cameraMovement: { type: Type.STRING, description: "Camera actions, e.g. drone orbital, static zoom-in" },
            editingStyle: { type: Type.STRING, description: "Aesthetic color grading and frame pacing descriptors" }
          },
          required: [
            "id", "fileName", "mimeType", "fileSizeLabel", "motionDescription", "emotionsDetected",
            "pacingStyle", "lightingStyle", "transitionsStyle", "cameraMovement", "editingStyle"
          ]
        }
      };

      const response = await ai.models.generateContent({
        model: "gemini-3.5-flash",
        contents: prompt,
        config: {
          systemInstruction: "You are a professional video analyst, cinematographer, and visual sequence post-production expert.",
          responseMimeType: "application/json",
          responseSchema: schema
        }
      });

      const parsedResult = JSON.parse(response.text || "[]");
      return res.json(parsedResult);
    } catch (err: any) {
      console.error("Gemini API error during reference video analysis:", err);
      return res.json(getFallbackReferenceAnalysis(files));
    }
  });

  // 3. Generate Master Storyboard and Clips Flow (4 Clips of 15 seconds)
  app.post("/api/generate-storyboard", async (req, res) => {
    const { styles, musicDetails, musicAnalysis, references } = req.body;

    if (!styles || !references || references.length === 0) {
      return res.status(400).json({ error: "Missing required style, music or reference video data for storyboard synthesis." });
    }

    if (!isApiKeyConfigured || !ai) {
      console.warn("GEMINI_API_KEY is not configured or placeholder. Delivering fallback generated storyboard.");
      return res.json(getFallbackStoryboard(styles, musicDetails, musicAnalysis, references));
    }

    try {
      const summaryPrompt = `
        Synthesize an AI video generation plan for a 60-second video split into exactly four 15-second sequential clips.
        
        Input Style Directives: ${Array.isArray(styles) ? styles.join(", ") : styles}
        Input Music Context:
        - Track Name: ${musicDetails?.fileName}
        - Estimated BPM: ${musicAnalysis?.tempo || 120} BPM
        - Key Mood: ${musicAnalysis?.keyMood || "Dynamic"}
        - Energy shifts: ${musicAnalysis?.energyCurve || "Steady build"}
        
        Input reference video analysis:
        ${JSON.stringify(references)}

        Instructions:
        1. Align the video seamlessly with the music's thematic progression.
        2. Integrate visual traits from the references (camera motion, editing pace, lighting).
        3. Force alignment into the selected style categories.
        4. Develop a "masterPrompt" summarizing the continuous flow.
        5. Formulate exactly 4 clips. Conforming to the 15-second timeline (0-15s, 15-30s, 30-45s, 45-60s).
      `;

      const schema = {
        type: Type.OBJECT,
        properties: {
          masterPrompt: {
            type: Type.STRING,
            description: "The main consolidated visual prompt that represents the continuous video generation arc."
          },
          clips: {
            type: Type.ARRAY,
            description: "The 4 sequential 15-second clips forming the 60 seconds total.",
            items: {
              type: Type.OBJECT,
              properties: {
                id: { type: Type.STRING },
                clipNumber: { type: Type.INTEGER },
                timeStart: { type: Type.INTEGER },
                timeEnd: { type: Type.INTEGER },
                title: { type: Type.STRING },
                visualPrompt: { type: Type.STRING, description: "Highly-detailed AI video generator prompt for text-to-video systems." },
                motionIntensity: { type: Type.INTEGER, description: "Estimated motion scale from 1 (static) to 10 (chaotic speed)." },
                colorPalette: {
                  type: Type.ARRAY,
                  items: { type: Type.STRING },
                  description: "Hex code palette suggestions (e.g. ['#FF0055', '#120024'])"
                },
                lightingMood: { type: Type.STRING, description: "Lighting instructions for the AI synthesizer" },
                cameraPath: { type: Type.STRING, description: "Detailed 3D camera vector description" },
                transitionIn: { type: Type.STRING, description: "Transition type from predecessor clip" },
                subtitles: { type: Type.STRING, description: "What text or lyrical subtitle plays on screen" },
                ambientCues: { type: Type.STRING, description: "Sound design recommendation" },
                frameDescription: { type: Type.STRING, description: "Vivid, highly visual painterly or camera description of the main keyframe, used to construct the canvas preview." },
                cssFilter: { type: Type.STRING, description: "Tailwind or CSS style overlay recommendation (e.g., 'hue-rotate-15 contrast-125 saturate-150')" },
                svgFrameSeed: { type: Type.STRING, description: "A simple list of 5-8 descriptive graphic shapes/colors separated by semicolons to construct visual drawings (e.g. 'sky:blue; sun:gold; city:purple; lasers:neon')" }
              },
              required: [
                "id", "clipNumber", "timeStart", "timeEnd", "title", "visualPrompt", "motionIntensity",
                "colorPalette", "lightingMood", "cameraPath", "transitionIn", "subtitles", "ambientCues",
                "frameDescription", "cssFilter", "svgFrameSeed"
              ]
            }
          }
        },
        required: ["masterPrompt", "clips"]
      };

      const response = await ai.models.generateContent({
        model: "gemini-3.5-flash",
        contents: summaryPrompt,
        config: {
          systemInstruction: "You are an AI video mastermind. Synthesize reference visual queues and audio cues to write high-fidelity storyboard generation instructions.",
          responseMimeType: "application/json",
          responseSchema: schema
        }
      });

      const parsedResult = JSON.parse(response.text || "{}");
      return res.json(parsedResult);
    } catch (err: any) {
      console.error("Gemini API error during storyboard synthesis:", err);
      return res.json(getFallbackStoryboard(styles, musicDetails, musicAnalysis, references));
    }
  });

  // Serve Vite or static files based on node environment
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Subcity Boi World Studio Server running on port ${PORT}`);
  });
}

