function getFallbackMusicAnalysis(fileName: string, lyrics?: string, genreGuess?: string) {
  const cleanName = fileName.replace(/\.[^/.]+$/, "").toLowerCase();
  
  // Custom heuristics based on track filename to make the simulation feel alive:
  let tempo = 124;
  let keyMood = "Ethereal & Cinematic";
  let pacing = "Medium Dynamic";
  let instrumentation = ["Synth Strings", "Pluck ARP", "Slo-Mo Sub Kick", "808 Claps"];
  let energyCurve = "Starts with calm ambient pads, introduces minor synth pulses, builds up to an expansive beat rise, and gently winds down.";
  let emotionalTriggers = ["Awe", "Introspection", "Technotrance Journey"];
  let thematicSegments = [
    "0:00 - Intro: Cinematic ambient drone setting the soundscape",
    "0:15 - Verse 1: Subtle drum kick, main chord progression begins",
    "0:30 - Chorus Drops: High-energy melodic sound elements blend",
    "0:45 - Outro Bridge: Quiet reverbed piano chords fading into silence"
  ];

  if (cleanName.includes("trap") || cleanName.includes("rap") || cleanName.includes("hip")) {
    tempo = 140;
    keyMood = "Gritty Urban / High Intensity";
    pacing = "Fast Aggressive";
    instrumentation = ["Muted Keys", "High Hat Roll (Triple)", "Deep 808 Drone", "Sub-bass rumble"];
    energyCurve = "Aggressive instantly with trap rhythm, holds high energy intensity throughout with rolling hats, sharp breakdown at the 45-second point.";
    emotionalTriggers = ["Confidence", "Rebellion", "Power"];
  } else if (cleanName.includes("lofi") || cleanName.includes("chill") || cleanName.includes("relax")) {
    tempo = 84;
    keyMood = "Nostalgic, Sunny Melancholic";
    pacing = "Slow Paced / Peaceful";
    instrumentation = ["Fringe Jazz Piano", "Vinyl Crackle", "Muted Trumpet Accent", "Dusty Snare rimshot"];
    energyCurve = "Warm relaxing entry, dusty snare loop repeats with minor vocal synth delays, drops into simple electric keyboard solo, smooth fading track loop.";
    emotionalTriggers = ["Relaxation", "Nostalgia", "Cozy solitude"];
  } else if (cleanName.includes("rock") || cleanName.includes("metal") || cleanName.includes("guitar")) {
    tempo = 132;
    keyMood = "Rebellious, High-Voltage Action";
    pacing = "Rapidly Aggressive";
    instrumentation = ["Distorted Lead Guitar", "Double Bass Pedals", "Screaming Feedback", "Crunchy Bass Guitar"];
    energyCurve = "Heavy feedback intro, immediate trash drum kit blast, epic metal harmony verse, massive solo build on double keys.";
    emotionalTriggers = ["Adrenaline", "Rage", "Pure Euphoria"];
  }

  return {
    pacing,
    tempo,
    instrumentation,
    keyMood,
    energyCurve,
    emotionalTriggers,
    suggestedTransitionSpeed: tempo > 120 ? "Rapid camera whip cuts on kick drums" : "Smooth dreamy 1.5-second dissolving blends",
    thematicSegments
  };
}

